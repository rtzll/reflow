import { expect } from 'playwright/test'
import { it } from 'remix/test'
import { open, showcaseServer } from './showcase-router.ts'

it('moves through the gallery button toolbar with arrows and leaves it with Tab', async (t) => {
  const page = await t.serve(showcaseServer)
  await open(page, '/')
  const toolbar = page.getByRole('toolbar', { name: 'Button variants' })
  const primary = toolbar.getByRole('button', { name: 'Primary' })
  const tertiary = toolbar.getByRole('button', { name: 'Tertiary' })
  await primary.focus()
  await primary.press('ArrowRight')
  await expect(toolbar.getByRole('button', { name: 'Secondary' })).toBeFocused()
  await page.keyboard.press('ArrowRight')
  await expect(tertiary).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(toolbar.locator(':focus')).toHaveCount(0)
  await page.keyboard.press('Shift+Tab')
  await expect(tertiary).toBeFocused()
})

it('operates the selected file from one keyboard tab stop', async (t) => {
  const page = await t.serve(showcaseServer)
  await page.context().grantPermissions(['clipboard-read', 'clipboard-write'])
  await open(page, '/docs/toolbar')
  const toolbar = page.getByRole('toolbar', { name: 'File preview' })
  const wrap = toolbar.getByRole('button', { name: 'Wrap lines' })
  const numbers = toolbar.getByRole('button', { name: 'Line numbers' })
  const copy = toolbar.getByRole('button', { name: 'Copy', exact: true })
  const block = page.locator('.example-file-preview .rf-code-block')
  await wrap.focus()
  await wrap.press('Space')
  await expect(block).toHaveAttribute('data-wrap', 'true')
  await wrap.press('ArrowRight')
  await expect(numbers).toBeFocused()
  await numbers.press('Space')
  await expect(block).toHaveAttribute('data-line-numbers', 'true')
  await numbers.press('ArrowRight')
  await expect(copy).toBeFocused()
  await copy.press('Enter')
  await expect
    .poll(() => page.evaluate(() => navigator.clipboard.readText()))
    .toBe(await block.locator('code').textContent())
  await copy.press('Tab')
  await expect(toolbar.locator(':focus')).toHaveCount(0)
  await page.getByRole('treeitem', { name: 'code-block-example.tsx' }).click()
  await expect(block.locator('code')).toContainText('export function')
  await expect(numbers).toHaveAttribute('aria-pressed', 'true')
  await copy.click()
  await expect
    .poll(() => page.evaluate(() => navigator.clipboard.readText()))
    .toBe(await block.locator('code').textContent())
})
