import { expect } from 'playwright/test'
import { it } from 'remix/test'
import { open, showcaseServer } from './showcase-router.ts'

it('keeps drafts with their conversations on a narrow screen', async (t) => {
  const page = await t.serve(showcaseServer)
  await page.setViewportSize({ width: 390, height: 844 })
  await open(page, '/apps/chat?thread=photo-sequence')
  const picker = page.getByRole('combobox', { name: 'Conversation' })
  const field = page.getByRole('textbox', { name: 'Message' })
  await expect(page.getByRole('log', { name: 'Photo essay sequence' })).toBeVisible()
  await field.fill('Try the empty waiting room at the end.')
  await picker.selectOption('interview-notes')
  await expect(field).toHaveValue('')
  await field.fill('Ask Mara about the weather.')
  await picker.selectOption('photo-sequence')
  await expect(field).toHaveValue('Try the empty waiting room at the end.')
  await expect(picker).toBeInViewport()
  await expect(field).toBeInViewport()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

it('creates a conversation, stops a reply mid-sentence, and returns to an unfinished draft', async (t) => {
  const page = await t.serve(showcaseServer)
  await page.setViewportSize({ width: 1280, height: 800 })
  await open(page, '/apps/chat')
  await page.clock.install()
  const field = page.getByRole('textbox', { name: 'Message' })
  await page.getByRole('button', { name: 'New conversation' }).click()
  await expect(field).toBeFocused()
  const title = 'Help me plan the cover'
  await field.fill(title)
  await field.press('Enter')
  const log = page.getByRole('log', { name: title })
  await expect(log.getByRole('article', { name: 'You' })).toHaveText(title)
  const answer = log.getByRole('article', { name: 'Assistant' })
  await page.clock.runFor(500)
  await expect(answer).toContainText('Print the two versions')
  await field.fill('Try the wider crop next.')
  await page.getByRole('button', { name: 'Stop response' }).click()
  await expect(answer).toContainText('Response stopped')
  const partial = await answer.innerText()
  await expect(answer).not.toContainText('small increments.')
  await page.getByRole('button', { name: 'Interview notes' }).click()
  await expect(field).toHaveValue('')
  await expect(page.getByRole('log')).not.toContainText(title)
  await page.clock.runFor(4000)
  await page.getByRole('button', { name: title, exact: true }).click()
  await expect(field).toHaveValue('Try the wider crop next.')
  expect(await answer.innerText()).toBe(partial)
})

it('finishes a reply in its own conversation while another is open', async (t) => {
  const page = await t.serve(showcaseServer)
  await page.setViewportSize({ width: 1280, height: 800 })
  await open(page, '/apps/chat')
  await page.clock.install()
  await page.getByRole('textbox', { name: 'Message' }).fill('How should I set the masthead?')
  await page.getByRole('button', { name: 'Send message' }).click()
  await expect(page.getByRole('button', { name: 'Stop response' })).toBeVisible()
  await page.getByRole('button', { name: 'Interview notes' }).click()
  await expect(page.getByRole('log').getByRole('article')).toHaveCount(2)
  await page.clock.runFor(4000)
  await page.getByRole('button', { name: 'Fieldnotes cover' }).click()
  await expect(page.getByRole('log').getByRole('article').last()).toContainText('small increments.')
  await expect(page.getByRole('button', { name: 'Stop response' })).toHaveCount(0)
})
